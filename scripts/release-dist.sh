#!/usr/bin/env bash
# Bundle the web build into a Release asset. Usage: scripts/release-dist.sh  -> web/tempboard-dist.tar.gz
# Then: gh release create v<version> web/tempboard-dist.tar.gz   (use the same version as .claude-plugin/plugin.json)
set -euo pipefail
cd "$(dirname "$0")/../web"
npm ci --no-audit --no-fund
python3 ../packaging/gen.py --check   # versions, generated files and license notices (against node_modules) must match before bundling
npm run build
cp ../LICENSE ../THIRD_PARTY_NOTICES.md dist/   # ship the license notices in the bundle (THIRD_PARTY_NOTICES.md is generated by packaging/notices.py)
tar -czf tempboard-dist.tar.gz dist
ls -lh tempboard-dist.tar.gz
